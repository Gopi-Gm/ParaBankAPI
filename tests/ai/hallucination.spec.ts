import { test, expect } from '../../fixtures/aiFixture';
import { HallucinationDetector } from '../../utils/ai/hallucination';

test.describe('Hallucination & Faithfulness Detection Tests @ai @hallucination', () => {
  // Test 1: URL Hallucination Check
  test('Verifies AI response does not hallucinate dead or non-existent URLs', async ({ request }) => {
    // Valid response referencing live links
    const validAiResponse = `
    You can visit our main portal at https://parabank.parasoft.com/parabank/index.htm.
    For additional banking services, visit https://parabank.parasoft.com/parabank/services.htm.
    `;

    await expect(validAiResponse).toNotHallucinateUrls(request);
  });

  test('Flags hallucinated 404 links generated by the AI', async ({ request }) => {
    const hallucinatedResponse = `
    Check your statement at https://parabank.parasoft.com/parabank/non-existent-broken-page-999.html.
    `;

    const result = await HallucinationDetector.verifyUrls(hallucinatedResponse, request);
    expect(result.valid).toBe(false);
    expect(result.brokenUrls.length).toBeGreaterThan(0);
    expect(result.brokenUrls[0].status).toBe(404);
  });

  // Test 2: Entity Grounding Verification (IDs must match database)
  test('Validates generated Account IDs actually belong to customer', () => {
    const knownCustomerAccountIds = [12345, 12456, 12567];

    // Model outputs account suggestions
    const modelGeneratedIds = [12345, 99999]; // 99999 is fabricated/hallucinated

    const check = HallucinationDetector.verifyEntityExistence(
      modelGeneratedIds,
      knownCustomerAccountIds
    );

    expect(check.valid).toBe(false);
    expect(check.hallucinatedEntities).toEqual([99999]);
  });

  // Test 3: RAG Context Grounding (Faithfulness)
  test('Detects ungrounded claims contradicted by source context', () => {
    const sourceContext = `
    ParaBank checking accounts earn 0.5% APY and require a minimum balance of $100.
    Overdraft fees are $35 per occurrence.
    `;

    // Faithful response
    const faithfulAnswer = 'Our checking accounts require a minimum balance of $100 and earn 0.5% APY.';
    const faithfulCheck = HallucinationDetector.checkHeuristicFaithfulness(faithfulAnswer, sourceContext);
    expect(faithfulCheck.grounded).toBe(true);
    expect(faithfulCheck.score).toBeGreaterThanOrEqual(0.7);

    // Hallucinated response claiming facts not present in source context
    const ungroundedAnswer =
      'Our platinum premium credit card gives ten percent cashback on international airline tickets.';
    const ungroundedCheck = HallucinationDetector.checkHeuristicFaithfulness(ungroundedAnswer, sourceContext);
    expect(ungroundedCheck.grounded).toBe(false);
    expect(ungroundedCheck.unsupportedClaims.length).toBeGreaterThan(0);
  });
});
